#!/bin/sh
# Gives the kiosk container the laptop's real backlight.
#
# A container without privileges sees /sys read-only, so it cannot set the
# brightness and the dashboard dims itself in software instead. This prints a
# compose override that mounts the backlight folder of this machine into the
# container, outside /sys (some security profiles block writes below /sys):
#
#   scripts/backlight-mount.sh > compose.override.yaml
#   docker compose --profile kiosk up -d
#
# The folder has to be written by root, which it is in the container.
set -eu

dir=""
for candidate in /sys/class/backlight/*; do
	[ -e "$candidate/brightness" ] || continue
	dir="$(readlink -f "$candidate")"
	break
done

if [ -z "$dir" ]; then
	echo "No backlight found in /sys/class/backlight: this machine has none (a desktop with a monitor?). Software dimming it is." >&2
	exit 1
fi

cat <<YAML
# Generated by scripts/backlight-mount.sh for $dir
services:
  kiosk:
    volumes:
      - $dir:/backlight
    environment:
      REFRAME_BACKLIGHT_PATH: /backlight
YAML
